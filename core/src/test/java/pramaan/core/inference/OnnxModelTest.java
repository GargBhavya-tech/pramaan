package pramaan.core.inference;

import static org.junit.jupiter.api.Assertions.assertArrayEquals;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;

import java.io.IOException;
import java.io.InputStream;
import org.junit.jupiter.api.Test;

/**
 * Build Map #2: ONNX Runtime loads and runs a model inside the engine. The fixture is generated by
 * {@code tools/make_smoke_model.py} and computes {@code y = 2x + 1} on a [1, 4] tensor.
 */
class OnnxModelTest {

    private static byte[] smokeModel() throws IOException {
        try (InputStream in = OnnxModelTest.class.getResourceAsStream("/models/smoke_affine.onnx")) {
            if (in == null) {
                throw new IllegalStateException(
                        "missing fixture; run: tools/.venv/Scripts/python tools/make_smoke_model.py");
            }
            return in.readAllBytes();
        }
    }

    @Test
    void runsTheAffineModelAndReturnsTheExpectedValuesAndShape() throws Exception {
        try (OnnxModel model = OnnxModel.load(smokeModel())) {
            assertEquals("x", model.inputName());
            assertEquals("y", model.outputName());
            assertArrayEquals(new long[] {1, 4}, model.inputShape());

            OnnxModel.Output out = model.run(new float[] {1f, 2f, 3f, -0.5f}, new long[] {1, 4});

            assertArrayEquals(new long[] {1, 4}, out.shape());
            assertArrayEquals(new float[] {3f, 5f, 7f, 0f}, out.values(), 1e-6f);
        }
    }

    @Test
    void rejectsAShapeThatDoesNotMatchTheData() throws Exception {
        try (OnnxModel model = OnnxModel.load(smokeModel())) {
            assertThrows(IllegalArgumentException.class, () -> model.run(new float[3], new long[] {1, 4}));
            assertThrows(IllegalArgumentException.class, () -> model.run(new float[4], new long[] {1, -4}));
        }
    }

    @Test
    void outputsAreDefensiveCopies() throws Exception {
        try (OnnxModel model = OnnxModel.load(smokeModel())) {
            OnnxModel.Output out = model.run(new float[] {0f, 0f, 0f, 0f}, new long[] {1, 4});
            out.values()[0] = 99f;
            assertEquals(1f, out.values()[0], 1e-6f);
        }
    }
}
