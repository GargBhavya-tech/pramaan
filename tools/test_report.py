#!/usr/bin/env python3
"""Turns the JUnit result files of the last Gradle run into docs/test-report.md.

    ./gradlew build            # writes <module>/build/test-results/test/*.xml
    python tools/test_report.py [--out docs/test-report.md]

It reports what ran, what was skipped and why, what failed, and which tests are negative cases (an attack refused, a
malformed input rejected). It invents nothing: every number is counted from the XML.
"""
import argparse
import datetime
import re
import sys
import xml.etree.ElementTree as ET
from collections import OrderedDict, defaultdict
from pathlib import Path

MODULES = ["core", "sbi", "desktop", "harness"]
NEGATIVE = re.compile(
    r"reject|refus|fail|never|cannot|cant|break|broken|drop|delay|forg|swap|stale|missing|unknown|invalid|malformed|"
    r"tamper|replay|reuse|mismatch|abstain|veto|blocked|denied|bad|empty|corrupt|truncat|overflow|bound",
    re.IGNORECASE,
)


def load(root: Path):
    rows = OrderedDict()
    for module in MODULES:
        files = sorted((root / module / "build" / "test-results" / "test").glob("TEST-*.xml"))
        suites = []
        for f in files:
            tree = ET.parse(f)
            suite = tree.getroot()
            cases = []
            for tc in suite.findall("testcase"):
                status = "passed"
                note = ""
                sk = tc.find("skipped")
                if sk is not None:
                    status, note = "skipped", (sk.get("message") or "").strip()
                if tc.find("failure") is not None or tc.find("error") is not None:
                    status = "failed"
                    el = tc.find("failure") if tc.find("failure") is not None else tc.find("error")
                    note = (el.get("message") or "").strip()
                cases.append((tc.get("name", ""), float(tc.get("time", "0") or 0), status, note))
            suites.append((suite.get("name", f.stem), cases))
        rows[module] = suites
    return rows


def short(cls: str) -> str:
    return cls.replace("pramaan.", "")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="docs/test-report.md")
    ap.add_argument("--root", default=".")
    args = ap.parse_args()
    root = Path(args.root)
    data = load(root)

    total = skipped = failed = 0
    seconds = 0.0
    per_module = OrderedDict()
    packages = defaultdict(lambda: [0, 0, 0])
    negatives = []
    skips = []
    fails = []
    for module, suites in data.items():
        t = s = f = 0
        sec = 0.0
        for cls, cases in suites:
            pkg = ".".join(cls.split(".")[:-1])
            for name, time, status, note in cases:
                t += 1
                sec += time
                packages[pkg][0] += 1
                if status == "skipped":
                    s += 1
                    packages[pkg][1] += 1
                    skips.append((cls, name, note))
                elif status == "failed":
                    f += 1
                    packages[pkg][2] += 1
                    fails.append((cls, name, note))
                if NEGATIVE.search(name):
                    negatives.append((module, short(cls), name, status))
        per_module[module] = (t, s, f, sec)
        total += t
        skipped += s
        failed += f
        seconds += sec

    if total == 0:
        print("no test results found: run ./gradlew build first", file=sys.stderr)
        return 1

    out = []
    w = out.append
    w("# Test cases and results")
    w("")
    w("Generated by `tools/test_report.py` from the JUnit result files of the last Gradle run (%s). Nothing here is typed by hand:"
      % datetime.date.today().isoformat())
    w("every number is counted from `<module>/build/test-results/test/*.xml`. Re-generate it after a build:")
    w("")
    w("```bash")
    w("./gradlew build")
    w("python tools/test_report.py")
    w("```")
    w("")
    w("## Summary")
    w("")
    w("| | Tests | Passed | Skipped | Failed | Time (s) |")
    w("|---|---:|---:|---:|---:|---:|")
    for module, (t, s, f, sec) in per_module.items():
        w("| `%s` | %d | %d | %d | %d | %.0f |" % (module, t, t - s - f, s, f, sec))
    w("| **all** | **%d** | **%d** | **%d** | **%d** | **%.0f** |" % (total, total - skipped - failed, skipped, failed, seconds))
    w("")
    w("**What \"skipped\" means here.** A test that needs a file that is not in the repository (the face models in `models/`, the")
    w("MockMDS stream sample, a Windows camera, a graphics toolkit) skips itself instead of failing. The author's machine has")
    w("those files, so few tests skip there; a fresh clone has none of them, so more skip. A skip is never counted as a pass.")
    w("")
    w("The same %d tests, three ways, so the numbers in the README are not a contradiction: **%d skipped** on the author's machine" % (total, skipped))
    w("(this report, with the models and the MockMDS fixtures present); **14 skipped** on a clean clone after `python tools/setup.py`")
    w("has fetched the models (measured 2026-10-25); **20 skipped** on a bare clone with no models (measured 2026-10-24). The 14 that")
    w("remain on a clean clone need the MockMDS fixtures, a corpus or a device, none of which is in the repository. These three figures")
    w("are measured on those runs and typed here, unlike the table above, which is counted from this machine's result files.")
    w("")
    if failed:
        w("## Failures")
        w("")
        for cls, name, note in fails:
            w("- `%s` `%s`: %s" % (short(cls), name, note[:200]))
        w("")
    w("## By area")
    w("")
    w("| Package | Tests | Skipped | Failed |")
    w("|---|---:|---:|---:|")
    for pkg in sorted(packages):
        t, s, f = packages[pkg]
        w("| `%s` | %d | %d | %d |" % (short(pkg), t, s, f))
    w("")
    w("## Edge cases and attacks the tests cover")
    w("")
    w("A test whose name says it rejects, refuses, breaks, drops, delays, forges, swaps or finds something stale, missing,")
    w("malformed or out of bounds is a **negative case**: it proves the system says no. %d of the %d tests are named like that." %
      (len(negatives), total))
    w("The full list is below, grouped by class.")
    w("")
    grouped = OrderedDict()
    for module, cls, name, status in negatives:
        grouped.setdefault((module, cls), []).append((name, status))
    for (module, cls), items in grouped.items():
        w("<details><summary><code>%s</code> (%s): %d negative cases</summary>" % (cls, module, len(items)))
        w("")
        for name, status in items:
            w("- %s%s" % (name, "" if status == "passed" else " (%s)" % status))
        w("")
        w("</details>")
        w("")
    if skips:
        w("## Skipped tests")
        w("")
        w("| Class | Test | Reason |")
        w("|---|---|---|")
        for cls, name, note in skips:
            w("| `%s` | %s | %s |" % (short(cls), name, (note or "(no reason recorded)").replace("|", "/")[:140]))
        w("")
    w("## Per class")
    w("")
    for module, suites in data.items():
        w("### %s" % module)
        w("")
        w("| Class | Tests | Skipped | Failed | Time (s) |")
        w("|---|---:|---:|---:|---:|")
        for cls, cases in suites:
            t = len(cases)
            s = sum(1 for c in cases if c[2] == "skipped")
            f = sum(1 for c in cases if c[2] == "failed")
            w("| `%s` | %d | %d | %d | %.1f |" % (short(cls), t, s, f, sum(c[1] for c in cases)))
        w("")
    w("## What these results are not")
    w("")
    w("They show that the code does what its tests say. They are **not** an error rate on real attacks: there is no real attack")
    w("corpus, so no APCER or BPCER is claimed (`docs/claim-sheet.md`, L1). Tests on synthetic data say so in their names or")
    w("their documentation, and are never used as headline results.")
    w("")

    path = root / args.out
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(out), encoding="utf-8")
    print("wrote %s: %d tests, %d skipped, %d failed, %d negative cases" % (path, total, skipped, failed, len(negatives)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
